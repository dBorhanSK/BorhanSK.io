create extension if not exists pgcrypto;

create table if not exists public.meow_jobs (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  target text not null,
  action text not null check (action in ('send', 'click')),
  payload text not null,
  interval_seconds integer not null check (interval_seconds >= 60),
  status text not null default 'active' check (status in ('active', 'paused')),
  next_run_at timestamptz not null,
  last_run_at timestamptz,
  runs_count integer not null default 0,
  max_runs integer,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists meow_jobs_due_idx
  on public.meow_jobs (status, next_run_at);

create table if not exists public.meow_events (
  id bigint generated by default as identity primary key,
  level text not null default 'info',
  message text not null,
  created_at timestamptz not null default now()
);

create index if not exists meow_events_created_idx
  on public.meow_events (created_at desc);

alter table public.meow_jobs enable row level security;
alter table public.meow_events enable row level security;

-- No anon/authenticated policies are added. The server uses SUPABASE_SERVICE_ROLE_KEY.
