create extension if not exists pgcrypto;

create table if not exists public.meow_members (
  id uuid primary key default gen_random_uuid(),
  username text not null unique,
  password_hash text not null,
  created_at timestamptz not null default now()
);
alter table public.meow_members add column if not exists active boolean not null default true;
alter table public.meow_members add column if not exists last_login_at timestamptz;

create table if not exists public.meow_accounts (
  id uuid primary key default gen_random_uuid(),
  owner_id text not null,
  platform text not null default 'telegram',
  label text not null,
  status text not null default 'pending',
  owner_access boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.meow_accounts add column if not exists owner_access boolean not null default false;
alter table public.meow_accounts add column if not exists tg_user_id text;
alter table public.meow_accounts add column if not exists tg_name text;
alter table public.meow_accounts add column if not exists tg_username text;
alter table public.meow_accounts add column if not exists tg_phone text;      -- stored MASKED only (+49•••••567)
alter table public.meow_accounts add column if not exists last_error text;
alter table public.meow_accounts add column if not exists last_seen_at timestamptz;
-- older versions restricted these columns with CHECK constraints; drop them so new values are accepted
alter table public.meow_accounts drop constraint if exists meow_accounts_platform_check;
alter table public.meow_accounts drop constraint if exists meow_accounts_status_check;
alter table public.meow_accounts add constraint meow_accounts_status_check
  check (status in ('pending', 'connected', 'error'));
create index if not exists meow_accounts_owner_idx on public.meow_accounts (owner_id, created_at desc);

create table if not exists public.meow_jobs (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  target text not null,
  action text not null check (action in ('send', 'click')),
  payload text not null,
  interval_seconds integer not null check (interval_seconds >= 60),
  status text not null default 'active' check (status in ('active', 'paused')),
  next_run_at timestamptz not null,
  last_run_at timestamptz,
  runs_count integer not null default 0,
  max_runs integer,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.meow_jobs add column if not exists owner_id text not null default 'owner';
alter table public.meow_jobs add column if not exists account_id uuid;
alter table public.meow_jobs add column if not exists mode text not null default 'random';
alter table public.meow_jobs add column if not exists cursor integer not null default 0;
alter table public.meow_jobs add column if not exists active_from integer;
alter table public.meow_jobs add column if not exists active_to integer;
create index if not exists meow_jobs_due_idx on public.meow_jobs (status, next_run_at);
create index if not exists meow_jobs_owner_idx on public.meow_jobs (owner_id, created_at desc);
create index if not exists meow_jobs_account_idx on public.meow_jobs (account_id);

create table if not exists public.meow_events (
  id bigint generated by default as identity primary key,
  level text not null default 'info',
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.meow_events add column if not exists owner_id text not null default 'owner';
create index if not exists meow_events_created_idx on public.meow_events (created_at desc);
create index if not exists meow_events_owner_idx on public.meow_events (owner_id, created_at desc);

-- Runtime metadata and service heartbeat. Telegram Desktop profile data stays on the Oracle persistent disk.
create table if not exists public.meow_runtime_state (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);
create index if not exists meow_runtime_state_updated_idx on public.meow_runtime_state (updated_at desc);

-- Server-side only: lock out every browser-facing role.
alter table public.meow_members enable row level security;
alter table public.meow_accounts enable row level security;
alter table public.meow_jobs enable row level security;
alter table public.meow_events enable row level security;
alter table public.meow_runtime_state enable row level security;

revoke all privileges on table public.meow_members, public.meow_accounts, public.meow_jobs,
  public.meow_events, public.meow_runtime_state from public, anon, authenticated;
grant all privileges on table public.meow_members, public.meow_accounts, public.meow_jobs,
  public.meow_events, public.meow_runtime_state to service_role;
revoke all privileges on sequence public.meow_events_id_seq from public, anon, authenticated;
grant usage, select on sequence public.meow_events_id_seq to service_role;

-- Legacy Telethon and Telegram-Web session blobs are not compatible with Telegram Desktop.
-- Remove only those obsolete session keys. Account, admin, job and event rows are retained.
delete from public.meow_runtime_state where key like 'tg_session:%' or key like 'telegram_web_storage_state%';
update public.meow_accounts set status = 'pending' where status <> 'pending';
