-- Borhan_SK Cloud Dashboard
-- Run this complete script in Supabase SQL Editor. Keep the service-role key on the server only.

create extension if not exists pgcrypto;

-- Existing automation table; the ALTER statements migrate older installations safely.
create table if not exists public.meow_jobs (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  target text not null,
  action text not null check (action in ('send', 'click')),
  payload text not null,
  interval_seconds integer not null check (interval_seconds >= 60),
  status text not null default 'active' check (status in ('active', 'paused')),
  next_run_at timestamptz not null,
  last_run_at timestamptz,
  runs_count integer not null default 0,
  max_runs integer,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.meow_jobs add column if not exists owner_id text not null default 'owner';
alter table public.meow_jobs add column if not exists account_id uuid;
create index if not exists meow_jobs_due_idx on public.meow_jobs (status, next_run_at);
create index if not exists meow_jobs_owner_idx on public.meow_jobs (owner_id, created_at desc);
create index if not exists meow_jobs_account_idx on public.meow_jobs (account_id);

create table if not exists public.meow_events (
  id bigint generated by default as identity primary key,
  level text not null default 'info',
  message text not null,
  created_at timestamptz not null default now()
);
alter table public.meow_events add column if not exists owner_id text not null default 'owner';
create index if not exists meow_events_created_idx on public.meow_events (created_at desc);
create index if not exists meow_events_owner_idx on public.meow_events (owner_id, created_at desc);

-- Admin credentials are stored as password hashes, never plaintext passwords.
create table if not exists public.meow_members (
  id uuid primary key default gen_random_uuid(),
  username text not null unique,
  password_hash text not null,
  created_at timestamptz not null default now()
);

-- Every Telegram Web connection is an isolated account/context.
-- owner_id='owner' is the site owner; admin accounts use their meow_members.id.
create table if not exists public.meow_accounts (
  id uuid primary key default gen_random_uuid(),
  owner_id text not null,
  platform text not null check (platform in ('telegram')),
  label text not null,
  status text not null default 'pending' check (status in ('pending', 'connected', 'error')),
  owner_access boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.meow_accounts add column if not exists owner_access boolean not null default false;
create index if not exists meow_accounts_owner_idx on public.meow_accounts (owner_id, created_at desc);

-- Encrypted Telegram Web storage states and runtime heartbeat. Ciphertext only.
create table if not exists public.meow_runtime_state (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

-- All tables are server-side only. Never add anon/authenticated policies for these tables.
alter table public.meow_jobs enable row level security;
alter table public.meow_events enable row level security;
alter table public.meow_members enable row level security;
alter table public.meow_accounts enable row level security;
alter table public.meow_runtime_state enable row level security;

-- The Flask server accesses the tables with SUPABASE_SERVICE_ROLE_KEY.
-- Do not put SUPABASE_SERVICE_ROLE_KEY in browser code, HTML, or GitHub.

-- Explicitly remove direct PostgREST access from browser-facing roles.
-- The Flask server uses only the service-role key stored in Render secrets.
revoke all privileges on table public.meow_jobs from public, anon, authenticated;
revoke all privileges on table public.meow_events from public, anon, authenticated;
revoke all privileges on table public.meow_members from public, anon, authenticated;
revoke all privileges on table public.meow_accounts from public, anon, authenticated;
revoke all privileges on table public.meow_runtime_state from public, anon, authenticated;
grant all privileges on table public.meow_jobs to service_role;
grant all privileges on table public.meow_events to service_role;
grant all privileges on table public.meow_members to service_role;
grant all privileges on table public.meow_accounts to service_role;
grant all privileges on table public.meow_runtime_state to service_role;

revoke all privileges on sequence public.meow_events_id_seq from public, anon, authenticated;
grant usage, select on sequence public.meow_events_id_seq to service_role;
